"""Writes src/design/Rotor67Stations.inc from data/rotor67/rotor67_bladegen.json.

The 14 NASA Rotor 67 sections (TP-2879) fitted with BladeGen's custom profile (apps/rotor67): span,
stagger, theta_LE and the chord-normalised profile parameters.  The designer's default layers blend
them to 0, 25, 50, 75 and 100 % span (design/BladeDesign.cpp).

    python tools/reference/make_rotor67_layers.py
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
d = json.loads((root / "data/rotor67/rotor67_bladegen.json").read_text())
lines = ["// Generated by tools/reference/make_rotor67_layers.py from data/rotor67/rotor67_bladegen.json.",
         "// NASA Rotor 67 (TP-2879), 14 sections fitted with the BladeGen custom profile: one JSON object per",
         "// section (span, stagger_deg, theta_le_deg, profile).  Do not edit by hand.",
         "static const char* const kRotor67Stations[] = {"]
for s in d["stations"]:
    e = {"span": s["span"], "stagger_deg": s["placement"]["stagger_deg"],
         "theta_le_deg": s["placement"]["theta_le_deg"], "profile": s["profile"]}
    lines.append('    R"json(' + json.dumps(e, separators=(",", ":")) + ')json",')
lines.append("};")
(root / "src/design/Rotor67Stations.inc").write_text("\n".join(lines) + "\n")
print("wrote", len(d["stations"]), "sections")
